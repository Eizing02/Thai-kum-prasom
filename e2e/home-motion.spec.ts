import { expect, test } from '@playwright/test'

test('the homepage floats the cards and rotates examples every five seconds', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  const start = new Date()
  await page.clock.install({ time: start })
  await page.clock.pauseAt(new Date(start.getTime() + 1000))
  await page.goto('/')
  const stage = page.locator('.lab-art')
  const caption = stage.locator('figcaption')
  await expect(caption).toContainText('รถ + ไฟ → รถไฟ')
  await expect(stage).toHaveAttribute('data-floating', 'true')
  await expect(stage.getByRole('button')).toHaveCount(0)
  const tile = stage.locator('.tile-one')
  await expect(tile).toHaveCSS('animation-name', /lab-tile-float/)
  const height = (await stage.boundingBox())!.height
  const yellow = await tile.evaluate(element => getComputedStyle(element).backgroundImage)

  await page.clock.runFor(4_900)
  await expect(caption).toContainText('คำประสม')
  await page.clock.runFor(150)
  await expect(stage).toHaveAttribute('data-turn', 'close')
  await expect(tile).toHaveCSS('animation-name', /lab-tile-float.*lab-tile-close/)
  await page.clock.runFor(700)
  await expect(caption).toContainText('ใหญ่ + โต → ใหญ่โต')
  await expect(page.locator('.home-copy [data-current=true]')).toHaveText('คำซ้อน')
  expect(await tile.evaluate(element => getComputedStyle(element).backgroundImage)).not.toBe(yellow)
  expect((await stage.boundingBox())!.height).toBe(height)

  await page.clock.runFor(5_250)
  await expect(caption).toContainText('รถ + ไฟ → รถไฟ')
  await page.clock.runFor(4_050)
  await expect(stage).toHaveAttribute('data-turn', 'close')
  await page.getByRole('button', { name: 'เริ่มเล่น' }).press('Enter')
  await expect(page).toHaveURL(/\/setup$/)
})

test('reduced motion shows a static example and both lesson pairs at 320 pixels', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 760 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.clock.install()
  await page.goto('/')
  const stage = page.locator('.lab-art')
  await page.clock.runFor(6_500)
  await expect(stage.locator('figcaption')).toContainText('รถ + ไฟ → รถไฟ')
  await expect(stage.getByRole('button')).toHaveCount(0)
  await expect(page.locator('.lesson-strip')).toContainText('ใหญ่ + โต → ใหญ่โต')
  await expect(stage).toHaveAttribute('data-turn', 'still')
  await expect(stage.locator('.tile-one')).toHaveCSS('animation-name', 'none')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

test('the examples wait offscreen and in a hidden tab, then resume', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 310 })
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.clock.install()
  await page.goto('/')
  const stage = page.locator('.lab-art')
  await expect(stage).toHaveAttribute('data-floating', 'false')
  await page.clock.runFor(6_500)
  await expect(stage).toHaveAttribute('data-example', '0')
  await stage.scrollIntoViewIfNeeded()
  await expect(stage).toHaveAttribute('data-floating', 'true')
  await page.evaluate(() => {
    Object.defineProperty(document, 'hidden', { configurable: true, value: true })
    document.dispatchEvent(new Event('visibilitychange'))
  })
  await expect(stage).toHaveAttribute('data-floating', 'false')
  await page.clock.runFor(6_500)
  await expect(stage).toHaveAttribute('data-example', '0')
  await page.evaluate(() => {
    Object.defineProperty(document, 'hidden', { configurable: true, value: false })
    document.dispatchEvent(new Event('visibilitychange'))
  })
  await expect(stage).toHaveAttribute('data-floating', 'true')
  await page.clock.runFor(6_500)
  await expect(stage).toHaveAttribute('data-example', '1')
})
